// застосовується ТІЛЬКИ на чутливих admin GET-ендпоінтах
// (списки замовлень/бронювань/товарів/категорій з даними клієнтів),
// щоб браузер/проміжний проксі не закешував відповідь. Не ставиться
// глобально — публічні GET (каталог тощо) кешування не бояться.
module.exports = function noStoreCache(req, res, next) {
    res.set("Cache-Control", "no-store");
    next();
};